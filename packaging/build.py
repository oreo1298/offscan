#!/usr/bin/env python3
"""Build the packages: one staged file tree, several package formats.

Subcommands (see ``python3 packaging/build.py COMMAND --help``):

``fetch``
    download the vendored wheels pinned in vendor.lock.json and check them
``stage``
    lay out the installed files under a directory; the PKGBUILD and
    install.sh use this too, so every format installs the same files
``packages``
    build the .deb and the Fedora and openSUSE .rpm files with nfpm
``pkgbuild``
    write the Arch PKGBUILD, its .install file and .SRCINFO
``tarball``
    write a source tarball of the tracked files
``version``
    print the version as a deb, rpm or pacman version
``notes``
    print this version's section of CHANGELOG.md (the release notes)

Names, paths and identifiers all come from src/offscan/appinfo.py.
"""

