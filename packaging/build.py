LAUNCHER = '''#!/usr/bin/python3 -I
# {comment}
# Generated by packaging/build.py.
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, {python_dir!r})
# The vendored packages go after the standard library but before the
# distribution's site-packages, so they win over older copies there.
sys.path.insert(next((i for i, p in enumerate(sys.path) if p.endswith(("-packages", "-packages/"))),
                     len(sys.path)), {vendor_dir!r})

from {module} import main

sys.exit(main())
'''


class BuildError(Exception):
    pass


# ----------------------------------------------------------------- versions

_PEP440 = re.compile(
    r"(?P<release>\d+(?:\.\d+)*)"
    r"(?:(?P<pre>a|b|rc)(?P<pre_n>\d+)|\.dev(?P<dev>\d+)|\.post(?P<post>\d+))?")


def package_version(version: str, fmt: str) -> str:
    """Map a PEP 440 version to one that sorts the same way in ``fmt``.

    Pre-releases and development releases must sort before the release:
    dpkg and rpm use ``~`` for that; pacman sorts a letter suffix before the
    bare version (``1.0rc1 < 1.0``). Only one suffix is supported, and
    ``.devN`` sorts between ``bN`` and ``rcN`` (do not mix the two kinds).
    """
    match = _PEP440.fullmatch(version)
    if not match:
        raise BuildError(f"unsupported version {version!r}: use X.Y.Z with at most one of "
                         "aN, bN, rcN, .devN or .postN")
    if fmt not in ("deb", "rpm", "pacman"):
        raise BuildError(f"unknown version format {fmt!r}")
    sep = "" if fmt == "pacman" else "~"
    out = match["release"]
    if match["pre"]:
        out += f"{sep}{match['pre']}{match['pre_n']}"
    elif match["dev"] is not None:
        out += f"{sep}dev{match['dev']}"
    elif match["post"] is not None:
        out += f".post{match['post']}"
    return out


def next_version(version: str) -> str:
    """A version that sorts after ``version`` (for upgrade tests)."""
    match = _PEP440.fullmatch(version)
    if not match:
        raise BuildError(f"unsupported version {version!r}")
    if match["dev"] is not None:
        return f"{match['release']}.dev{int(match['dev']) + 1}"
    if match["pre"]:
        return f"{match['release']}{match['pre']}{int(match['pre_n']) + 1}"
    parts = match["release"].split(".")
    parts[-1] = str(int(parts[-1]) + 1)
    return ".".join(parts)


def source_date_epoch() -> int:
    value = os.environ.get("SOURCE_DATE_EPOCH")
    if value:
        return int(value)
    if _own_checkout():
        out = subprocess.run(["git", "-C", str(ROOT), "log", "-1", "--format=%ct"],
                             capture_output=True, text=True, check=False)
        if out.returncode == 0 and out.stdout.strip():
            return int(out.stdout.strip())
    return int(datetime.datetime.now(datetime.UTC).timestamp())


def values(epoch: int | None = None, version: str | None = None) -> dict[str, str]:
    """appinfo's values for the templates; ``version`` overrides the package version only."""
    out = render.appinfo_values()
    if version:
        package_version(version, "deb")         # validates it
        out["VERSION"] = version
    when = datetime.datetime.fromtimestamp(source_date_epoch() if epoch is None else epoch, datetime.UTC)
    out["RELEASE_DATE"] = when.strftime("%Y-%m-%d")
    # Screenshots of the release itself (the tag), so they always match the version.
    repo = out["HOMEPAGE"].removeprefix("https://github.com/").strip("/")
    out["SCREENSHOT_BASE"] = f"https://raw.githubusercontent.com/{repo}/v{out['VERSION']}/docs/screenshots"
    return out


def host_arch() -> str:
    return normalise_arch(platform.machine())


def normalise_arch(arch: str) -> str:
    try:
        return ARCH_ALIASES[arch]
    except KeyError:
        raise BuildError(f"unsupported architecture {arch!r} (supported: x86_64, aarch64)") from None


# ------------------------------------------------------------------- wheels

def lock_packages() -> list[dict]:
    return json.loads(LOCK.read_text(encoding="utf-8"))["packages"]


def wheel_entries(arch: str) -> list[tuple[dict, dict]]:
    """(package, file entry) for every vendored package on ``arch``."""
    out = []
    for pkg in lock_packages():
        entry = pkg["files"].get(arch) or pkg["files"].get("any")
        if entry is None:
            raise BuildError(f"{pkg['name']} has no wheel for {arch}")
        out.append((pkg, entry))
    return out


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _download(url: str, target: Path, sha256: str) -> None:
    if not url.startswith("https://"):
        raise BuildError(f"refusing to download over plain HTTP: {url}")
    print(f"downloading {target.name}", file=sys.stderr)
    request = urllib.request.Request(url, headers={"User-Agent": "packaging/build.py"})  # noqa: S310
    digest = hashlib.sha256()
    fd, tmp = tempfile.mkstemp(dir=target.parent, prefix=".part-")
    try:
        with os.fdopen(fd, "wb") as out, urllib.request.urlopen(request, timeout=60) as resp:  # noqa: S310
            size = 0
            for block in iter(lambda: resp.read(1 << 20), b""):
                size += len(block)
                if size > MAX_WHEEL:
                    raise BuildError(f"{url} is larger than {MAX_WHEEL >> 20} MiB")
                digest.update(block)
                out.write(block)
        if digest.hexdigest() != sha256:
            raise BuildError(f"{target.name}: SHA-256 {digest.hexdigest()} does not match the lock file")
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def _copy_private(src: Path, directory: Path) -> Path:
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    target = directory / src.name
    fd = os.open(src, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(fd, "rb") as inp, open(target, "wb") as out:
        shutil.copyfileobj(inp, out)
    return target


def find_wheels(arch: str, directory: Path, download: bool = False,
                copy_to: Path | None = None) -> dict[str, Path]:
    """Return name -> verified wheel path; download missing ones if allowed.

    With ``copy_to``, each wheel is first copied there and the copy is what is
    checked and returned (``directory`` may belong to someone else).
    """
    found = {}
    for pkg, entry in wheel_entries(arch):
        target = directory / entry["file"]
        if target.is_file() and not target.is_symlink():
            candidate = _copy_private(target, copy_to) if copy_to else target
            if sha256_file(candidate) == entry["sha256"]:
                found[pkg["name"]] = candidate
                continue
            if not download:
                raise BuildError(f"{target}: SHA-256 does not match the lock file")
        elif not download:
            raise BuildError(f"{entry['file']} is not in {directory}")
        destination = copy_to or directory
        destination.mkdir(parents=True, exist_ok=True)
        _download(entry["url"], destination / entry["file"], entry["sha256"])
        found[pkg["name"]] = destination / entry["file"]
    return found


# ------------------------------------------------------------------ staging

@dataclass
class Entry:
    path: str          # absolute installed path
    mode: int
    kind: str = "file"  # "file" or "dir"


@dataclass
class Tree:
    """A staged file tree: ``dest`` plus the installed path of each file."""

    dest: Path
    epoch: int
    files: dict[str, int] = field(default_factory=dict)

    def _target(self, path: str) -> Path:
        pure = PurePosixPath(path)
        if not pure.is_absolute() or ".." in pure.parts:
            raise BuildError(f"bad install path {path!r}")
        return self.dest / pure.relative_to("/")

    def write(self, path: str, data: bytes, mode: int = 0o644) -> None:
        if path in self.files:
            raise BuildError(f"{path} staged twice")
        target = self._target(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        self.files[path] = mode

    def copy(self, path: str, src: Path, mode: int = 0o644) -> None:
        self.write(path, src.read_bytes(), mode)

    def finish(self, owned_roots: tuple[str, ...]) -> list[Entry]:
        """Normalise modes and times; return files plus the directories we own."""
        dirs: set[str] = set()
        for path in self.files:
            parent = PurePosixPath(path).parent
            while str(parent) != "/":
                if any(str(parent) == root or str(parent).startswith(root + "/") for root in owned_roots):
                    dirs.add(str(parent))
                parent = parent.parent
        for path, mode in self.files.items():
            target = self._target(path)
            os.chmod(target, mode)
            os.utime(target, (self.epoch, self.epoch))
        for path in self.dest.rglob("*"):
            if path.is_dir() and not path.is_symlink():
                os.chmod(path, 0o755)  # noqa: S103 - installed directories are world-readable
        for path in sorted(self.dest.rglob("*"), key=lambda p: -len(p.parts)):
            if path.is_dir():
                os.utime(path, (self.epoch, self.epoch))
        entries = [Entry(d, 0o755, "dir") for d in sorted(dirs)]
        entries += [Entry(p, m) for p, m in sorted(self.files.items())]
        return entries


def owned_roots(info: dict[str, str]) -> tuple[str, ...]:
    """Directories that belong to this package alone (removed with it)."""
    name = info["NAME"]
    return (info["LIB_DIR"], f"/usr/share/doc/{name}", f"/usr/share/licenses/{name}")


SKIP_PARTS = {"__pycache__", ".git", "build", "dist", ".venv", "venv", ".pytest_cache", ".ruff_cache",
              ".mypy_cache", ".hypothesis", "out"}


def _own_checkout() -> bool:
    """True if ROOT is a git checkout of the current user, where running git is safe.

    Run as root in someone else's checkout, the checkout's configuration
    could run commands (git refuses that too, see safe.directory).
    """
    try:
        owner = (ROOT / ".git").stat().st_uid
    except OSError:
        return False
    return shutil.which("git") is not None and owner == os.geteuid()


def _git_files(subdir: str) -> list[Path] | None:
    """The tracked files (like ``git archive``), or None when git cannot or should not be asked."""
    if not _own_checkout():
        return None
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z", "--cached", "--", subdir or "."],
                         capture_output=True, check=False)
    if out.returncode != 0:
        return None
    return [ROOT / name for name in out.stdout.decode().split("\0") if name]


def tracked_files(subdir: str = "") -> list[Path]:
    """Files under ROOT/subdir: git's list when this is the user's checkout, else a walk."""
    files = _git_files(subdir)
    if files is not None:
        return sorted(p for p in files if p.is_file() and not p.is_symlink())
    found = []
    for path in (ROOT / subdir).rglob("*"):
        rel = path.relative_to(ROOT).parts
        if any(part in SKIP_PARTS or part.endswith(".egg-info") for part in rel):
            continue
        if path.is_file() and not path.is_symlink() and path.suffix not in (".pyc", ".pyo"):
            found.append(path)
    return sorted(found)


def _gzip(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, mtime=0, compresslevel=9) as gz:
        gz.write(data)
    return buf.getvalue()


def man_pages() -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-I", str(ROOT / "tools" / "manpage.py"), tmp],
                       check=True, stdout=subprocess.DEVNULL)
        return {p.name: p.read_text(encoding="utf-8") for p in sorted(Path(tmp).iterdir())}


def _safe_member(name: str) -> PurePosixPath:
    pure = PurePosixPath(name)
    if pure.is_absolute() or ".." in pure.parts or not pure.parts:
        raise BuildError(f"unsafe path in wheel: {name!r}")
    return pure


def unpack_wheel(tree: Tree, wheel: Path, vendor_dir: str) -> dict[str, bytes]:
    """Unpack ``wheel`` into ``vendor_dir``; return the licence files it carries."""
    licences = {}
    with zipfile.ZipFile(wheel) as zf:
        for info in zf.infolist():
            if info.is_dir():
                continue
            if (info.external_attr >> 16) & 0o170000 == 0o120000:
                raise BuildError(f"{wheel.name}: symbolic link {info.filename!r}")
            member = _safe_member(info.filename)
            if member.parts[0].endswith(".data"):
                raise BuildError(f"{wheel.name}: .data directories are not supported ({info.filename})")
            data = zf.read(info)
            tree.write(f"{vendor_dir}/{member}", data)
            if member.parts[0].endswith(".dist-info") and (
                    LICENSE_RE.match(member.name) or "licenses" in member.parts):
                licences[member.name] = data
    return licences


def third_party_notice(info: dict[str, str], licences: dict[str, list[str]]) -> str:
    lines = [f"# Third-party software in {info['DISPLAY_NAME']}", "",
             "These Python packages are not shipped by the distributions, so they are installed "
             f"from pinned wheels into {info['VENDOR_DIR']}. Each wheel is checked against the "
             "SHA-256 recorded in packaging/vendor.lock.json.", ""]
    for pkg in lock_packages():
        lines += [f"## {pkg['name']} {pkg['version']}", "",
                  f"* Licence: {pkg['license']}", f"* Home page: {pkg['homepage']}"]
        lines += [f"* Licence text: {path}" for path in licences.get(pkg["name"], [])]
        if pkg.get("note"):
            lines.append(f"* {pkg['note']}")
        lines.append("")
    return "\n".join(lines)


def stage(dest: Path, flavor: str, arch: str, wheels: dict[str, Path] | None,
          info: dict[str, str] | None = None, epoch: int | None = None) -> list[Entry]:
    """Lay out every installed file under ``dest``; return what was staged.

    ``wheels`` maps vendored package names to verified wheel files; ``None``
    stages without them (the features they provide are then unavailable).
    """
    if flavor not in FLAVORS:
        raise BuildError(f"unknown flavor {flavor!r}")
    epoch = source_date_epoch() if epoch is None else epoch
    info = info or values(epoch)
    name = info["NAME"]
    tree = Tree(dest, epoch)
    doc_dir = f"/usr/share/doc/{name}"
    licenses_dir = None if flavor == "deb" else f"/usr/share/licenses/{name}"

    package_root = ROOT / "src"
    for path in tracked_files("src/offscan"):
        if "__pycache__" in path.parts or path.suffix in (".pyc", ".pyo"):
            continue
        tree.copy(f"{info['PYTHON_DIR']}/{path.relative_to(package_root).as_posix()}", path)

    for target, module, comment in (
            (f"/usr/bin/{name}", "offscan.cli.main", f"{info['DISPLAY_NAME']} command line"),
            (f"/usr/bin/{info['GUI_NAME']}", "offscan.gui.app", f"{info['DISPLAY_NAME']} window"),
            (info["HELPER_PATH"], "offscan.helper.main",
             f"Privileged helper of {info['DISPLAY_NAME']}, started through pkexec "
             f"({info['POLKIT_ACTION']})")):
        text = LAUNCHER.format(comment=comment, python_dir=info["PYTHON_DIR"],
                               vendor_dir=info["VENDOR_DIR"], module=module)
        tree.write(target, text.encode(), 0o755)

    if wheels:
        # Licence texts of the vendored packages; Debian keeps them all in
        # the copyright file, the others in the licences directory.
        vendor_licences = f"{licenses_dir or doc_dir}/vendor"
        licences: dict[str, list[str]] = {}
        packages = {pkg["name"]: pkg for pkg in lock_packages()}
        if set(wheels) != set(packages):
            raise BuildError(f"wheels for {sorted(packages)} expected, got {sorted(wheels)}")
        for pkg_name, wheel in sorted(wheels.items()):
            texts = unpack_wheel(tree, wheel, info["VENDOR_DIR"])
            for extra in packages[pkg_name].get("license_files", []):
                texts[Path(extra).name] = (HERE / extra).read_bytes()
            if not texts:
                raise BuildError(f"{pkg_name}: no licence text (add license_files to the lock)")
            for file_name, data in sorted(texts.items()):
                tree.write(f"{vendor_licences}/{pkg_name}/{file_name}", data)
                licences.setdefault(pkg_name, []).append(f"{vendor_licences}/{pkg_name}/{file_name}")
        tree.write(f"{doc_dir}/THIRD-PARTY.md", third_party_notice(info, licences).encode())

    for template, target in (
            ("polkit.policy.in", f"/usr/share/polkit-1/actions/{info['APP_ID']}.policy"),
            ("desktop.in", f"/usr/share/applications/{info['DESKTOP_FILE']}"),
            ("metainfo.xml.in", f"/usr/share/metainfo/{info['APP_ID']}.metainfo.xml")):
        tree.write(target, render.render(template, info).encode())
    tree.copy(f"/usr/share/icons/hicolor/scalable/apps/{info['ICON_NAME']}.svg", HERE / "icon.svg")
    for page, text in man_pages().items():
        tree.write(f"/usr/share/man/man1/{page}.gz", _gzip(text.encode()))
    for doc in DOCS:
        tree.copy(f"{doc_dir}/{Path(doc).name}", ROOT / doc)
    if flavor == "deb":
        tree.write(f"{doc_dir}/copyright", render.render("copyright.in", info).encode())
    else:
        tree.copy(f"{licenses_dir}/LICENSE", ROOT / "LICENSE")

    if flavor == "arch":
        # The interpreter that builds an Arch package is the one that runs it.
        for directory in (info["PYTHON_DIR"], info["VENDOR_DIR"]):
            target = tree._target(directory)
            if target.is_dir():
                compile_tree(target, strip=dest)
        for pyc in dest.rglob("*.pyc"):
            tree.files["/" + pyc.relative_to(dest).as_posix()] = 0o644
    return tree.finish(owned_roots(info))


def compile_tree(directory: Path, strip: Path | None = None) -> bool:
    """Byte-compile ``directory`` (hash-checked, so file times do not matter)."""
    kwargs = {}
    if strip is not None:
        kwargs = {"stripdir": str(strip), "prependdir": "/"}
    return bool(compileall.compile_dir(
        str(directory), quiet=1, workers=0,
        invalidation_mode=py_compile.PycInvalidationMode.CHECKED_HASH, **kwargs))


# --------------------------------------------------------------------- nfpm

def dependency(group: list[str], fmt: str) -> str:
    if fmt == "deb":
        return " | ".join(group)
    return group[0] if len(group) == 1 else "(" + " or ".join(group) + ")"


def render_scripts(out: Path, info: dict[str, str]) -> dict[str, str]:
    out.mkdir(parents=True, exist_ok=True)
    scripts = {}
    for key in ("preinstall", "postinstall", "preremove", "postremove"):
        target = out / f"{key}.sh"
        target.write_text(render.render(f"scripts/{key}.sh.in", info), encoding="utf-8")
        target.chmod(0o755)
        scripts[key] = str(target)
    return scripts


def nfpm_config(stage_dir: Path, entries: list[Entry], target: str, arch: str,
                info: dict[str, str], scripts: dict[str, str], epoch: int) -> dict:
    fmt = "deb" if target == "deb" else "rpm"
    deps = json.loads(DEPS.read_text(encoding="utf-8"))[target]
    mtime = datetime.datetime.fromtimestamp(epoch, datetime.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
    contents = []
    for entry in entries:
        meta = {"mode": entry.mode, "owner": "root", "group": "root", "mtime": mtime}
        if entry.kind == "dir":
            contents.append({"dst": entry.path, "type": "dir", "file_info": meta})
        else:
            contents.append({"src": str(stage_dir / entry.path.lstrip("/")), "dst": entry.path,
                             "file_info": meta})
    config = {
        "name": info["NAME"],
        "arch": ARCHES[arch]["nfpm"],
        "platform": "linux",
        "version": package_version(info["VERSION"], fmt),
        "version_schema": "none",
        "release": "1",
        "section": "utils",
        "priority": "optional",
        "maintainer": info["MAINTAINER"],
        "description": info["SUMMARY"] + "\n" + textwrap.fill(info["DESCRIPTION"], 79),
        "vendor": info["DISPLAY_NAME"],
        "homepage": info["HOMEPAGE"],
        "license": info["LICENSE"],
        "depends": [dependency(g, fmt) for g in deps["depends"]],
        "recommends": [dependency(g, fmt) for g in deps.get("recommends", [])],
        "suggests": [dependency(g, fmt) for g in deps.get("suggests", [])],
        "contents": contents,
        "scripts": scripts,
        "mtime": mtime,
    }
    if fmt == "deb":
        config["deb"] = {"compression": "xz", "fields": {"Bugs": f"{info['HOMEPAGE']}/issues"}}
    else:
        config["rpm"] = {"compression": "zstd", "summary": info["SUMMARY"], "packager": info["MAINTAINER"],
                         "group": "Productivity/Security" if target == "opensuse" else "Applications/System"}
    return config


def package_file_name(target: str, arch: str, info: dict[str, str]) -> str:
    if target == "deb":
        return f"{info['NAME']}_{package_version(info['VERSION'], 'deb')}-1_{ARCHES[arch]['deb']}.deb"
    return f"{info['NAME']}-{package_version(info['VERSION'], 'rpm')}-1.{target}.{ARCHES[arch]['rpm']}.rpm"


def build_packages(arch: str, targets: list[str], out: Path, wheels: dict[str, Path],
                   nfpm: str, keep: Path | None = None, version: str | None = None) -> list[Path]:
    epoch = source_date_epoch()
    info = values(epoch, version)
    out.mkdir(parents=True, exist_ok=True)
    built = []
    with tempfile.TemporaryDirectory(prefix="pkg-") as tmp:
        work = keep or Path(tmp)
        scripts = render_scripts(work / "scripts", info)
        for target in targets:
            flavor = "deb" if target == "deb" else "rpm"
            stage_dir = work / f"stage-{target}"
            if stage_dir.exists():
                shutil.rmtree(stage_dir)
            entries = stage(stage_dir, flavor, arch, wheels, info, epoch)
            config = nfpm_config(stage_dir, entries, target, arch, info, scripts, epoch)
            config_path = work / f"nfpm-{target}.json"
            config_path.write_text(json.dumps(config, indent=1), encoding="utf-8")
            result = out / package_file_name(target, arch, info)
            env = {**os.environ, "SOURCE_DATE_EPOCH": str(epoch)}
            subprocess.run([nfpm, "package", "--config", str(config_path), "--packager",
                            "deb" if target == "deb" else "rpm", "--target", str(result)],
                           check=True, env=env)
            built.append(result)
    return built


# ----------------------------------------------------------------- PKGBUILD

def _bash_words(items: list[str], indent: int = 0) -> str:
    """Single-quoted bash words; one per line (aligned to ``indent``) when given."""
    for item in items:
        if "'" in item or "\n" in item:
            raise BuildError(f"cannot quote {item!r} for the PKGBUILD")
    words = [f"'{item}'" for item in items]
    return ("\n" + " " * indent).join(words) if indent else " ".join(words)


def pkgbuild_data(tarball: Path, url: str | None, info: dict[str, str]) -> dict:
    deps = json.loads(DEPS.read_text(encoding="utf-8"))["arch"]
    any_sources, any_sums, per_arch = [], [], {a: ([], []) for a in ARCHES}
    noextract = []
    for pkg in lock_packages():
        for key, entry in sorted(pkg["files"].items()):
            noextract.append(entry["file"])
            if key == "any":
                any_sources.append(entry["url"])
                any_sums.append(entry["sha256"])
            else:
                per_arch[key][0].append(entry["url"])
                per_arch[key][1].append(entry["sha256"])
    source = f"{tarball.name}::{url}" if url else tarball.name
    return {
        "pkgname": info["NAME"],
        "pkgver": package_version(info["VERSION"], "pacman"),
        "pkgdesc": info["SUMMARY"],
        "url": info["HOMEPAGE"],
        "license": info["LICENSE"],
        "depends": [g[0] for g in deps["depends"]],
        "optdepends": [f"{name}: {why}" for name, why in deps["optdepends"]],
        "source": [source, *any_sources],
        "sha256sums": [sha256_file(tarball), *any_sums],
        "per_arch": per_arch,
        "noextract": sorted(set(noextract)),
        "srcdir": tarball.name.removesuffix(".tar.gz"),
    }


def render_pkgbuild(data: dict, info: dict[str, str]) -> str:
    fields = dict(info)
    fields.update({
        "PKGVER": data["pkgver"],
        "DEPENDS": _bash_words(data["depends"]),
        "OPTDEPENDS": _bash_words(data["optdepends"], len("optdepends=(")),
        "SOURCES": _bash_words(data["source"], len("source=(")),
        "SHA256SUMS": _bash_words(data["sha256sums"], len("sha256sums=(")),
        "NOEXTRACT": _bash_words(data["noextract"], len("noextract=(")),
        "SRCDIR": data["srcdir"],
    })
    for arch, (sources, sums) in data["per_arch"].items():
        fields[f"SOURCES_{arch.upper()}"] = _bash_words(sources, len(f"source_{arch}=("))
        fields[f"SHA256SUMS_{arch.upper()}"] = _bash_words(sums, len(f"sha256sums_{arch}=("))
    if "'" in info["SUMMARY"]:
        raise BuildError("the summary must not contain a single quote")
    return render.render("PKGBUILD.in", fields)


def render_srcinfo(data: dict, info: dict[str, str]) -> str:
    """The .SRCINFO that ``makepkg --printsrcinfo`` writes for our PKGBUILD."""
    lines = [f"pkgbase = {data['pkgname']}"]

    def add(key: str, items: list[str] | str) -> None:
        for item in [items] if isinstance(items, str) else items:
            lines.append(f"\t{key} = {item}")

    add("pkgdesc", data["pkgdesc"])
    add("pkgver", data["pkgver"])
    add("pkgrel", "1")
    add("url", data["url"])
    add("install", f"{info['NAME']}.install")
    add("arch", list(ARCHES))
    add("license", data["license"])
    add("makedepends", "python")
    add("depends", data["depends"])
    add("optdepends", data["optdepends"])
    add("noextract", data["noextract"])
    add("options", ["!strip", "!debug"])
    add("source", data["source"])
    add("sha256sums", data["sha256sums"])
    for arch, (sources, sums) in data["per_arch"].items():
        add(f"source_{arch}", sources)
        add(f"sha256sums_{arch}", sums)
    lines += ["", f"pkgname = {data['pkgname']}", ""]
    return "\n".join(lines)


def write_pkgbuild(out: Path, tarball: Path, url: str | None, version: str | None = None) -> list[Path]:
    info = values(version=version)
    data = pkgbuild_data(tarball, url, info)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "PKGBUILD": render_pkgbuild(data, info),
        ".SRCINFO": render_srcinfo(data, info),
        f"{info['NAME']}.install": render.render("pacman.install.in", info),
    }
    written = []
    for name, text in files.items():
        (out / name).write_text(text, encoding="utf-8")
        written.append(out / name)
    if not url and tarball.resolve().parent != out.resolve():
        shutil.copy2(tarball, out / tarball.name)
        written.append(out / tarball.name)
    return written


# ------------------------------------------------------------------ tarball

def write_tarball(out: Path) -> Path:
    info = values()
    epoch = source_date_epoch()
    prefix = f"{info['NAME']}-{info['VERSION']}"
    out.mkdir(parents=True, exist_ok=True)
    target = out / f"{prefix}.tar.gz"
    with open(target, "wb") as raw, \
            gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=9) as gz, \
            tarfile.open(fileobj=gz, mode="w", format=tarfile.PAX_FORMAT) as tar:
        for path in tracked_files():
            rel = path.relative_to(ROOT).as_posix()
            data = path.read_bytes()
            member = tarfile.TarInfo(f"{prefix}/{rel}")
            member.size = len(data)
            member.mtime = epoch
            member.mode = 0o755 if os.access(path, os.X_OK) else 0o644
            member.uname = member.gname = ""
            tar.addfile(member, io.BytesIO(data))
    return target


# -------------------------------------------------------------------- notes

def release_notes(version: str, changelog: Path = ROOT / "CHANGELOG.md") -> str:
    """The body of the ``## <version>`` section of the changelog."""
    out: list[str] = []
    inside = False
    for line in changelog.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            if inside:
                break
            inside = line[3:].split()[0] == version
            continue
        if inside:
            out.append(line)
    if not inside and not out:
        raise BuildError(f"CHANGELOG.md has no section for {version}")
    return "\n".join(out).strip() + "\n"


# --------------------------------------------------------------------- main

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="build.py", description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    cache = ROOT / "build" / "wheels"

    p = sub.add_parser("fetch", help="download and verify the vendored wheels")
    p.add_argument("--arch", default=None, help="x86_64 or aarch64 (default: this machine)")
    p.add_argument("--cache", type=Path, default=cache, help=f"directory for the wheels (default: {cache})")

    p = sub.add_parser("stage", help="lay out the installed files under a directory")
    p.add_argument("--dest", type=Path, required=True)
    p.add_argument("--flavor", choices=FLAVORS, default="manual")
    p.add_argument("--arch", default=None)
    p.add_argument("--wheels", type=Path, help="directory holding the wheels (no download)")
    p.add_argument("--no-vendor", action="store_true", help="leave out the vendored packages")

    p = sub.add_parser("packages", help="build .deb and .rpm packages with nfpm")
    p.add_argument("--arch", default=None)
    p.add_argument("--targets", default=",".join(TARGETS), help=f"comma-separated subset of {TARGETS}")
    p.add_argument("--out", type=Path, default=ROOT / "dist")
    p.add_argument("--wheels", type=Path, default=cache)
    p.add_argument("--offline", action="store_true", help="do not download missing wheels")
    p.add_argument("--nfpm", default=shutil.which("nfpm") or "nfpm")
    p.add_argument("--keep", type=Path, help="keep the staged trees and nfpm configs here")
    p.add_argument("--version", help="package version to use instead of appinfo's (upgrade tests)")

    p = sub.add_parser("pkgbuild", help="write PKGBUILD, .SRCINFO and the .install file")
    p.add_argument("--tarball", type=Path, required=True, help="source tarball (hashed into the PKGBUILD)")
    p.add_argument("--url", help="where the AUR fetches the tarball (default: next to the PKGBUILD)")
    p.add_argument("--out", type=Path, default=ROOT / "dist" / "arch")
    p.add_argument("--version", help="package version to use instead of appinfo's (upgrade tests)")

    p = sub.add_parser("tarball", help="write a source tarball")
    p.add_argument("--out", type=Path, default=ROOT / "dist")

    sub.add_parser("notes", help="print this version's section of CHANGELOG.md")

    p = sub.add_parser("version", help="print the version in a package format")
    p.add_argument("format", choices=("pep440", "deb", "rpm", "pacman", "next"),
                   help="'next' prints a PEP 440 version that sorts after the current one")

    args = parser.parse_args(argv)
    try:
        if args.command == "version":
            version = render.appinfo_values()["VERSION"]
            if args.format == "pep440":
                print(version)
            elif args.format == "next":
                print(next_version(version))
            else:
                print(package_version(version, args.format))
        elif args.command == "fetch":
            arch = normalise_arch(args.arch or host_arch())
            for path in find_wheels(arch, args.cache, download=True).values():
                print(path)
        elif args.command == "stage":
            arch = normalise_arch(args.arch or host_arch())
            wheels = None if args.no_vendor else find_wheels(arch, args.wheels or cache,
                                                              download=args.wheels is None)
            entries = stage(args.dest, args.flavor, arch, wheels)
            print(f"staged {sum(e.kind == 'file' for e in entries)} files in {args.dest}")
        elif args.command == "packages":
            arch = normalise_arch(args.arch or host_arch())
            targets = [t for t in args.targets.split(",") if t]
            if not targets or set(targets) - set(TARGETS):
                parser.error(f"--targets must be a subset of {TARGETS}")
            wheels = find_wheels(arch, args.wheels, download=not args.offline)
            for path in build_packages(arch, targets, args.out, wheels, args.nfpm, args.keep, args.version):
                print(path)
        elif args.command == "pkgbuild":
            for path in write_pkgbuild(args.out, args.tarball, args.url, args.version):
                print(path)
        elif args.command == "tarball":
            print(write_tarball(args.out))
        elif args.command == "notes":
            print(release_notes(render.appinfo_values()["VERSION"]), end="")
    except (BuildError, subprocess.CalledProcessError, OSError) as exc:
        print(f"build.py: error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
